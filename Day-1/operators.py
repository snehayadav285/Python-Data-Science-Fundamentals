# Day 1 - Python Operators

a = 10
b = 3

# Arithmetic operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

# Comparison operators
print("a is greater than b:", a > b)
print("a is equal to b:", a == b)

# Logical operators
x = True
y = False

print("AND:", x and y)
print("OR:", x or y)
print("NOT:", not x)
